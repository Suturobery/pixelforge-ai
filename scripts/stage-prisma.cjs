// PixelForge AI — packaging helper: stage a self-contained Prisma CLI
// (resources/prisma/) for the packaged app's first-run db push.
//
// Bundles the root prisma CLI + engine executables into one directory the
// RenderServer can run under Electron-as-Node:
//   resources/prisma/prisma-cli.cjs   — requires the real CLI bundle
//   resources/prisma/schema.prisma    — copied from prisma/schema.prisma
//   resources/prisma/vendor/          — prisma build/, @prisma/engines, etc.
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'apps', 'desktop', 'resources', 'prisma');
const VENDOR = path.join(OUT, 'vendor');

// This is the SQLite DDL Prisma generates for prisma/schema.prisma.  Keeping
// it here avoids running Prisma's schema engine inside a packaged Electron
// executable on the user's computer.  Update this together with the schema
// whenever a model changes.
const TEMPLATE_SCHEMA_SQL = `
CREATE TABLE "User" (
  "id" TEXT NOT NULL PRIMARY KEY,
  "email" TEXT NOT NULL,
  "name" TEXT,
  "createdAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" DATETIME NOT NULL
);
CREATE UNIQUE INDEX "User_email_key" ON "User"("email");
CREATE TABLE "Post" (
  "id" TEXT NOT NULL PRIMARY KEY,
  "title" TEXT NOT NULL,
  "content" TEXT,
  "published" BOOLEAN NOT NULL DEFAULT false,
  "authorId" TEXT NOT NULL,
  "createdAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" DATETIME NOT NULL
);
CREATE TABLE "Project" (
  "id" TEXT NOT NULL PRIMARY KEY,
  "name" TEXT NOT NULL,
  "width" INTEGER NOT NULL,
  "height" INTEGER NOT NULL,
  "palette" TEXT NOT NULL,
  "data" TEXT NOT NULL,
  "createdAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" DATETIME NOT NULL
);
`;

function copyIfExists(src, dest) {
  if (!fs.existsSync(src)) return false;
  fs.cpSync(src, dest, { recursive: true });
  return true;
}

function main() {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(VENDOR, { recursive: true });

  // prisma CLI bundle + its private deps (paths verified against root nm)
  copyIfExists(path.join(ROOT, 'node_modules', 'prisma'), path.join(VENDOR, 'prisma'));
  copyIfExists(path.join(ROOT, 'node_modules', '@prisma', 'engines'), path.join(VENDOR, 'engines'));
  copyIfExists(path.join(ROOT, 'node_modules', '@prisma', 'get-platform'), path.join(VENDOR, 'get-platform'));
  copyIfExists(path.join(ROOT, 'node_modules', '@prisma', 'debug'), path.join(VENDOR, 'debug'));
  copyIfExists(path.join(ROOT, 'node_modules', '@prisma', 'internals'), path.join(VENDOR, 'internals'));

  // schema + loader shim
  fs.copyFileSync(path.join(ROOT, 'prisma', 'schema.prisma'), path.join(OUT, 'schema.prisma'));
  fs.writeFileSync(
    path.join(OUT, 'prisma-cli.cjs'),
    [
      "// generated by scripts/stage-prisma.cjs — do not edit",
      "const path = require('node:path');",
      "const vendor = path.join(__dirname, 'vendor');",
      "const Module = require('node:module');",
      "Module.globalPaths.push(vendor);",
      "const requireShim = Module.createRequire(path.join(vendor, 'prisma', 'package.json'));",
      "module.exports = requireShim('prisma/build/index.js');",
    ].join('\n'),
  );

  // A packaged Electron executable cannot reliably re-launch itself as a
  // Node CLI on every user's machine. Generate an empty, schema-ready SQLite
  // database while staging instead; RenderServer copies this on first launch.
  const templateDb = path.join(OUT, 'template.db');
  const { DatabaseSync } = require('node:sqlite');
  const template = new DatabaseSync(templateDb);
  try {
    template.exec(TEMPLATE_SCHEMA_SQL);
  } finally {
    template.close();
  }
  if (!fs.existsSync(templateDb) || fs.statSync(templateDb).size === 0) {
    throw new Error('Prisma template database was not created');
  }

  const cliSize = fs.statSync(path.join(VENDOR, 'prisma')).size;
  console.log(`prisma staged → resources/prisma (cli bundle ~${Math.round(cliSize / 1024)} KB + engines)`);
}

main();
